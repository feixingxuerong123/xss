# Digest: findings -> a bounded prompt payload
# ---------------------------------------------------------------------------

def _d(f) -> dict:
    return f.data if hasattr(f, "data") else f


def _clip(s: Any, n: int) -> str:
    t = "" if s is None else str(s)
    t = t.replace("\r", " ").replace("\n", " ")
    return t if len(t) <= n else t[: n - 1] + "…"


def summarize_findings(findings: list, max_findings: int = MAX_FINDINGS_DEFAULT
                       ) -> tuple[list[dict], dict]:
    """Turn findings into a compact, severity-ordered digest.

    Returns ``(rows, stats)``.  Rows are capped so the prompt stays bounded on
    a scan that produced hundreds of findings; ``stats`` reports both the
    total and the omitted count so the model (and the reader) knows the
    digest is partial rather than pretending it is complete.
    """
    from . import fix_advice

    by_sev: dict[str, int] = {}
    by_type: dict[str, int] = {}
    for f in findings:
        d = _d(f)
        sev = str(d.get("severity") or "info")
        ftype = str(d.get("type") or "unknown")
        by_sev[sev] = by_sev.get(sev, 0) + 1
        by_type[ftype] = by_type.get(ftype, 0) + 1

    ordered = sorted(
        findings,
        key=lambda f: (_SEV_ORDER.get(str(_d(f).get("severity") or "info"), 9),),
    )

    rows: list[dict] = []
    for i, f in enumerate(ordered[:max_findings], 1):
        d = _d(f)
        ftype = str(d.get("type") or "unknown")
        try:
            adv = fix_advice.get_advice(ftype)
        except Exception:
            adv = {}
        poc = d.get("poc") or {}
        rows.append({
            "n": i,
            "type": ftype,
            "severity": str(d.get("severity") or "info"),
            "url": _clip(d.get("url"), _URL_CAP),
            "method": str(d.get("method") or "GET"),
            "param": d.get("param") or "",
            "context": str(d.get("context") or ""),
            "payload": _clip(d.get("payload"), _PAYLOAD_CAP),
            "transform": list(d.get("transform") or []),
            "detail": _clip(d.get("detail") or d.get("evidence"), _DETAIL_CAP),
            "confidence": str(d.get("confidence") or ""),
            "cvss": d.get("cvss_score"),
            "cwe": d.get("cwe") or adv.get("primary_cwe", ""),
            "poc_curl": _clip(poc.get("curl"), _PAYLOAD_CAP),
            "engine_fix_headline": _clip(adv.get("headline"), _DETAIL_CAP),
            "engine_fix_detail": _clip(adv.get("detail"), _DETAIL_CAP),
        })

    stats = {
        "total": len(findings),
        "by_severity": by_sev,
        "by_type": by_type,
        "included": len(rows),
        "omitted": max(0, len(findings) - len(rows)),
    }
    return rows, stats


