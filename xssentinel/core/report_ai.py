# Output cleaning
# ---------------------------------------------------------------------------

#: Tags some models emit around their reasoning channel.
_REASON_TAGS = ("</think", "</thinking", "</reasoning", "</analysis",
                "</scratchpad", "</internal")
#: Deliberately narrow: only unambiguous reasoning-channel tags.  Including
#: generic names like ``answer``/``output`` would silently eat a payload that
#: happens to contain a literal ``<output>`` tag.
_REASON_TAG_RE = re.compile(
    r"</?\s*(think|thinking|reasoning|analysis|scratchpad|internal)\b[^>]*>",
    re.I)
#: A whole-report code fence, opening and optional trailing fence.
_FENCE_RE = re.compile(r"^\s*```[a-zA-Z0-9_+-]*[ \t]*\r?\n(?P<body>.*?)(?:\r?\n```\s*)?$",
                       re.S)


def clean_completion(text: str) -> str:
    """Strip reasoning-channel leakage and stray fences from a completion.

    Observed live with ``amd/MiniCPM5-2B``: the whole chain of thought came
    back before the answer, separated by a closing ``</think`` tag::

        我们被要求根据提供的JSON数据撰写报告。报告必须遵循…… </think>

        ## 执行摘要
        …real report…

    Order matters here: the opening code fence must go FIRST.  Stripping the
    preamble before the fence would remove the opening ```` ``` ```` while
    leaving the trailing one behind, which then defeats the fence regex.

    Stage by stage:

    1. a whole-report code fence (the prompt forbids it; models still do it);
    2. reasoning channel -- if a close tag is present, keep only what follows;
    3. otherwise, if a ``##`` heading exists past the first line, drop
       everything before it (the prompt fixes the output shape, so a first
       line that is not a heading is by definition preamble).

    Nothing is ever *added*, so a well-behaved model -- whose output starts at
    ``## 执行摘要`` on line 1 -- passes through untouched.
    """
    if not text:
        return ""
    t = text.strip()

    # 1. Whole-report fence first (see docstring for why).
    m = _FENCE_RE.match(t)
    if m and m.group("body").strip():
        t = m.group("body").strip()
    # A stray trailing fence whose opener was already consumed.
    if t.endswith("```"):
        t = t[:-3].rstrip()

    # 2. Reasoning channel: drop everything up to and including the close tag.
    lower = t.lower()
    cut = -1
    for tag in _REASON_TAGS:
        i = lower.find(tag)
        if i != -1:
            gt = t.find(">", i)
            cand = gt + 1 if gt != -1 else i + len(tag)
            if cand > cut:
                cut = cand
    if cut > 0:
        t = t[cut:]
    t = _REASON_TAG_RE.sub("", t).strip()

    # 3. Preamble without a tag: a report always opens on a '##' heading.
    if not t.startswith("#"):
        h = re.search(r"^##\s", t, flags=re.M)
        if h and h.start() > 0:
            t = t[h.start():]

    return t.strip()


# ---------------------------------------------------------------------------
# Fact verification (the model writes prose, not facts)
# ---------------------------------------------------------------------------

def _verify_facts(text: str, rows: list[dict],
                  extra_urls: list[str] | None = None) -> list[str]:
    """Flag URLs / payloads the model quoted that are NOT in the digest.

    ``extra_urls`` carries legitimate non-finding URLs the model is expected to
    reference -- above all the scan TARGET, which is in the prompt's metadata
    and which any summary naturally names.  Without it every report about a
    clean scan gets a false "unverified content" warning: with zero findings
    there are no finding URLs at all, so the target was the only URL in the
    text and got reported as invented.  (Observed live on an API scan of a
    reflector that produced 0 findings.)

    A cheap, deliberately conservative check: it only looks at quoted URLs and
    backticked payload-looking strings, and reports what it cannot attribute.
    It never edits the text -- a false accusation is worse than a missed one
    here, so the bar is "this looks like a real URL/payload and it appears
    nowhere in the input".
    """
    if not text:
        return []
    known_urls = {r["url"] for r in rows if r.get("url")}
    known_urls |= {u for u in (extra_urls or []) if u}
    known_payloads = {r["payload"] for r in rows if r.get("payload")}
    # Hosts are enough: models legitimately shorten a long URL to its path.
    known_hosts = set()
    for u in known_urls:
        m = re.search(r"https?://([^/\s]+)", u)
        if m:
            known_hosts.add(m.group(1).lower())

    warnings: list[str] = []
    for m in re.finditer(r"https?://[^\s`)\]>,，。；\"]+", text):
        u = m.group(0).rstrip(".")
        mh = re.search(r"https?://([^/\s]+)", u)
        if not mh:
            continue
        if mh.group(1).lower() in known_hosts:
            continue
        if any(u in ku or ku.startswith(u) for ku in known_urls):
            continue
        if u not in warnings:
            warnings.append(u)
    for m in re.finditer(r"`([^`\n]{8,200})`", text):
        s = m.group(1).strip()
        if not any(t in s for t in ("<", "onerror", "onload", "alert(", "javascript:")):
            continue
        if s in known_payloads:
            continue
        if any(s in kp or kp in s for kp in known_payloads if kp):
            continue
        if s not in warnings:
            warnings.append(s)
    return warnings[:10]


