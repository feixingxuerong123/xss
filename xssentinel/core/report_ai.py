def build_ai_report(findings: list, target: str, meta: dict | None = None, *,
                    pool=None, config_path: str | None = None,
                    models: list[str] | None = None,
                    lang: str = "zh",
                    max_findings: int = MAX_FINDINGS_DEFAULT,
                    timeout: float | None = None,
                    verify_facts: bool = True) -> AIReport:
    """Produce the narrative section, never raising on LLM failure.

    On success: a model written section + routing info.
    On any failure (no config, all candidates rate-limited/blocked, bad
    output): the deterministic template, with ``error`` explaining why.
    """
    meta = meta or {}
    lang = lang if lang in _COPY else "zh"
    rep = AIReport(finding_count=len(findings))
    t0 = time.time()

    rows, stats = summarize_findings(findings, max_findings)

    resolved_pool = pool
    if resolved_pool is None:
        try:
            from .llm_pool import LLMPool
            resolved_pool = LLMPool.from_file(config_path)
        except Exception as e:
            # No pool configured / unreadable: straight to template.
            reason = f"{type(e).__name__}: {e}"
            _log.warning("ai report: no usable LLM pool (%s); using template",
                         reason)
            rep.error = reason
            rep.markdown = template_report(findings, target, meta, reason, lang)
            rep.html = _md_to_html(rep.markdown)
            rep.elapsed = time.time() - t0
            return rep

    messages = build_prompt(rows, stats, target, meta, lang)
    try:
        result = resolved_pool.complete(messages, models=models,
                                        timeout=timeout,
                                        min_chars=MIN_REPORT_CHARS)
    except Exception as e:
        reason = _short_reason(e)
        _log.warning("ai report: pool exhausted (%s); using template", reason)
        rep.error = reason
        rep.attempts = [a.to_dict() for a in getattr(e, "attempts", [])]
        rep.markdown = template_report(findings, target, meta, reason, lang)
        rep.html = _md_to_html(rep.markdown)
        rep.elapsed = time.time() - t0
        return rep

    # Some models leak their reasoning channel ahead of the answer; strip it
    # before anything downstream sees the text (see clean_completion).
    text = clean_completion(result.text or "")
    if not text:
        # A 200 with nothing in it -- same treatment as a failure.
        reason = "model returned an empty completion"
        rep.error = reason
        rep.attempts = [a.to_dict() for a in result.attempts]
        rep.markdown = template_report(findings, target, meta, reason, lang)
        rep.html = _md_to_html(rep.markdown)
        rep.elapsed = time.time() - t0
        return rep

    c = _COPY[lang]
    header = [
        f"> {c['ai_note'].format(model=result.candidate.model)}",
        f"> {c['provider_line'].format(provider=result.candidate.provider_id, model=result.candidate.model, failovers=result.failovers)}",
        "",
    ]
    if verify_facts:
        # The target is legitimate context -- it is in the prompt's metadata,
        # so naming it is not invention.
        warnings = _verify_facts(text, rows, extra_urls=[target])
        if warnings:
            rep.fact_warnings = warnings
            items = "；".join(f"`{w}`" for w in warnings)
            header.append(f"> ⚠️ {c['unverified'].format(n=len(warnings), items=items)}")
            header.append("")

    md = "\n".join(header) + text.rstrip() + "\n"
    rep.markdown = md
    rep.html = _md_to_html(md)
    rep.ok = True
    rep.used_llm = True
    rep.provider = result.candidate.provider_id
    rep.model = result.candidate.model
    rep.failovers = result.failovers
    rep.attempts = [a.to_dict() for a in result.attempts]
    rep.elapsed = time.time() - t0
    return rep


def _short_reason(e: BaseException) -> str:
    """Human-readable one-liner for why the LLM path failed."""
    try:
        from .llm_pool import LLMPoolExhausted
        if isinstance(e, LLMPoolExhausted):
            kinds: dict[str, int] = {}
            for a in getattr(e, "attempts", []):
                kinds[a.kind] = kinds.get(a.kind, 0) + 1
            if kinds:
                detail = ", ".join(f"{k} x{v}" for k, v in kinds.items())
                return f"all candidates failed ({detail})"
    except Exception:
        pass
    return f"{type(e).__name__}: {str(e)[:160]}"


def ai_section_html(ai_meta: dict) -> str:
    """Render the AI section for the HTML report from ``meta['ai_report']``."""
    if not isinstance(ai_meta, dict):
        return ""
    body = ai_meta.get("html") or ""
    if not body:
        return ""
    cls = "ai-report degraded" if ai_meta.get("degraded") else "ai-report"
    return (f'<section class="{cls}">'
            f'<h2>{_html.escape(_COPY["zh"]["title"])}</h2>'
            f'{body}</section>')


def ai_section_markdown(ai_meta: dict) -> str:
    """Render the AI section for the Markdown report."""
    if not isinstance(ai_meta, dict):
        return ""
    md = ai_meta.get("markdown") or ""
    if not md:
        return ""
    return f"## {_COPY['zh']['title']}\n\n{md}\n"
