"""LLM-written narrative report + its deterministic fallback (Phase 176).

Division of labour, stated once so it stays true
------------------------------------------------
The engine decides.  The model only writes prose about what the engine
decided.  Concretely:

  * the model receives target info + a compact digest of real findings
    (type, severity, url, param, method, context, payload, transform, the
    engine's own detail line, and the corpus remediation advice)
  * the model is told, in the prompt, that it may not invent or alter a
    single fact -- and :func:`_verify_facts` re-checks afterwards that every
    URL and payload the model echoed really exists in the digest.  Anything
    it made up is flagged in the report footer rather than shown as truth
  * no finding is added, removed, re-typed or re-graded by the model.  The
    authoritative findings live in the machine-readable report; this module
    only produces a narrative *section*

Degradation is mandatory, not optional
--------------------------------------
An LLM pool can be entirely rate-limited / blocked / offline.  When that
happens :func:`build_ai_report` does NOT raise -- it produces the same
report structure from ``fix_advice``'s curated corpus (the deterministic
path that predates this module) and labels it as such.  A scan always ends
with a usable report.

Security note: LLM output is escaped before any HTML tag is generated
(see :func:`_md_to_html`).  The report is a document people open in a
browser, and the text it contains is, by construction, full of live attack
strings -- a model that echoes a payload must not be able to turn the report
itself into a vector.  Escape first, then decorate.
"""
