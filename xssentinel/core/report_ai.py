def template_report(findings: list, target: str, meta: dict,
                    reason: str = "", lang: str = "zh") -> str:
    """Build the same structure without any model, from the advice corpus.

    This is the safety net: an unreachable pool must still yield a report a
    human can act on.  Content comes from ``data/fix_advice.json`` verbatim,
    so nothing here is invented -- which is exactly why it is an acceptable
    substitute when the model is not available.
    """
    from . import fix_advice

    c = _COPY.get(lang, _COPY["zh"])
    rows, stats = summarize_findings(findings, max_findings=10 ** 6)

    lines: list[str] = []
    if reason:
        lines.append(f"> {c['degraded_note'].format(reason=reason)}")
        lines.append("")

    # -- executive summary -------------------------------------------------
    lines.append(f"## {c['summary']}")
    lines.append("")
    if not findings:
        lines.append(c["none"])
    else:
        counts = stats["by_severity"]
        dist = " · ".join(f"{k}: {counts[k]}"
                          for k in sorted(counts, key=lambda s: _SEV_ORDER.get(s, 9)))
        worst = min(counts, key=lambda s: _SEV_ORDER.get(s, 9))
        if _SEV_ORDER.get(worst, 9) <= 1:
            verdict = c["critical_first"]
        elif _SEV_ORDER.get(worst, 9) <= 2:
            verdict = c["medium_first"]
        else:
            verdict = c["low_only"]
        lines.append(f"{c['meta_line'].format(target=target, n=stats['total'], generated=meta.get('generated', ''))}")
        lines.append("")
        lines.append(f"{dist}。{verdict}")
    lines.append("")

    # -- risk rating -------------------------------------------------------
    if findings:
        lines.append(f"## {c['rating']}")
        lines.append("")
        lines.append(f"| {c['sev']} | {c['count']} |")
        lines.append("|---|---|")
        counts = stats["by_severity"]
        for sev in sorted(counts, key=lambda s: _SEV_ORDER.get(s, 9)):
            lines.append(f"| {sev} | {counts[sev]} |")
        lines.append("")

    # -- details -----------------------------------------------------------
    if findings:
        lines.append(f"## {c['details']}")
        lines.append("")
        for r in rows:
            url_short = r["url"]
            if len(url_short) > 80:
                url_short = url_short[:77] + "…"
            lines.append(f"### {r['n']}. [{r['severity']}] {r['type']} — {url_short}")
            lines.append("")
            adv = fix_advice.get_advice(r["type"])
            if r.get("param"):
                lines.append(f"- **{c['param']}**：`{r['param']}`")
            lines.append(f"- **{c['method']}**：`{r['method']}`")
            if r.get("context"):
                lines.append(f"- **{c['context']}**：`{r['context']}`")
            if r.get("payload"):
                lines.append(f"- **{c['payload']}**：`{r['payload']}`")
            if r.get("detail"):
                lines.append(f"- {r['detail']}")
            if adv.get("detail"):
                lines.append(f"- **{c['impact']} / {c['cause']}**：{adv['detail']}")
            if r.get("poc_curl"):
                lines.append(f"- **{c['verify']}**：`{r['poc_curl']}`")
            if adv.get("headline"):
                lines.append(f"- **{c['fix']}**：{adv['headline']}")
            cwe = r.get("cwe") or adv.get("primary_cwe")
            if cwe:
                lines.append(f"- **{c['cwe']}**：{cwe}")
            also = adv.get("also_consider") or []
            if also:
                lines.append(f"- **{c['also']}**：" + "；".join(also))
            lines.append("")

    # -- priority ----------------------------------------------------------
    if findings:
        lines.append(f"## {c['priority']}")
        lines.append("")
        seen: list[str] = []
        for r in rows:
            if r["type"] not in seen:
                seen.append(r["type"])
        for i, t in enumerate(seen, 1):
            adv = fix_advice.get_advice(t)
            n = stats["by_type"].get(t, 0)
            lines.append(f"{i}. `{t}`（{n} 处）— {adv.get('headline', '')}")
        lines.append("")

    if stats.get("omitted"):
        lines.append(c["truncated"].format(n=stats["omitted"]))
        lines.append("")
    return "\n".join(lines).strip() + "\n"


