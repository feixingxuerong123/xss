@dataclass
class AIReport:
    """The narrative section, in both renderings, plus how it was produced."""

    markdown: str = ""
    html: str = ""
    ok: bool = False                # True only when a model wrote it
    used_llm: bool = False
    provider: str = ""
    model: str = ""
    failovers: int = 0
    elapsed: float = 0.0
    error: str = ""                 # why we degraded (empty when ok)
    attempts: list[dict] = field(default_factory=list)
    fact_warnings: list[str] = field(default_factory=list)
    finding_count: int = 0

    @property
    def degraded(self) -> bool:
        return not self.used_llm

    def to_meta(self) -> dict:
        """JSON-safe view, for ``meta['ai_report']`` and the JSON report."""
        return {
            "ok": self.ok,
            "used_llm": self.used_llm,
            "degraded": self.degraded,
            "provider": self.provider,
            "model": self.model,
            "failovers": self.failovers,
            "elapsed": round(self.elapsed, 2),
            "error": self.error,
            "fact_warnings": list(self.fact_warnings),
            "finding_count": self.finding_count,
            "attempts": list(self.attempts),
            "markdown": self.markdown,
            "html": self.html,
        }


