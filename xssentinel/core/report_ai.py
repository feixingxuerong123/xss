# Minimal, escape-first Markdown -> HTML
# ---------------------------------------------------------------------------

def _inline(s: str) -> str:
    """Decorate an ALREADY-ESCAPED line with inline markup."""
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"(?<!\*)\*(?!\s)(.+?)(?<!\s)\*(?!\*)", r"<em>\1</em>", s)
    # Double backticks first: models wrap commands in ``...`` (CommonMark's
    # way of quoting a span that may itself contain one backtick).  Live case:
    # ``curl -i 'http://...'`` rendered with literal backticks, mangling the
    # one part of the report a reader actually copy-pastes.
    s = re.sub(r"``([^`\n]+)``", r"<code>\1</code>", s)
    s = re.sub(r"`([^`\n]+)`", r"<code>\1</code>", s)
    return s


def _md_to_html(md: str) -> str:
    """Convert the model's Markdown to report HTML.

    Escape-first: every character is entity-escaped before any tag is
    synthesised, so a payload the model quotes can never execute in the
    reader's browser.  Supports headings, lists, tables, bold/italic/code and
    paragraphs -- the subset the prompt asks for.
    """
    if not md:
        return ""
    text = md.strip()
    # Strip a whole-report code fence if the model wrapped everything.
    text = re.sub(r"^\s*```[a-zA-Z]*\s*\n(.*)\n```\s*$", r"\1", text,
                  flags=re.S)
    out: list[str] = []
    list_open: str | None = None
    in_table = False
    para: list[str] = []

    def flush_para():
        if para:
            out.append("<p>" + _inline(" ".join(para)) + "</p>")
            para.clear()

    def close_list():
        nonlocal list_open
        if list_open:
            out.append(f"</{list_open}>")
            list_open = None

    def close_table():
        nonlocal in_table
        if in_table:
            out.append("</tbody></table>")
            in_table = False

    for raw in text.split("\n"):
        line = _html.escape(raw.rstrip(), quote=False)
        stripped = line.strip()

        if stripped.startswith("|") and stripped.endswith("|"):
            close_list()
            flush_para()
            cells = [c.strip() for c in stripped.strip("|").split("|")]
            if all(set(c) <= set("-: ") and c for c in cells):
                continue  # separator row
            if not in_table:
                out.append('<table class="ai-table"><tbody>')
                in_table = True
            out.append("<tr>" + "".join(f"<td>{_inline(c)}</td>" for c in cells)
                       + "</tr>")
            continue
        close_table()

        if not stripped:
            flush_para()
            close_list()
            continue

        m = re.match(r"^(#{1,6})\s+(.*)$", stripped)
        if m:
            flush_para()
            close_list()
            # Shifted down one level and capped at h4: the section already
            # carries an <h2> from ai_section_html, so the model's '##' must
            # become h3 and its '###' h4 -- otherwise a top-level section
            # heading and a per-finding heading would collide at the same
            # depth and the report would read flat.
            lvl = min(4, len(m.group(1)) + 1)
            out.append(f"<h{lvl}>{_inline(m.group(2))}</h{lvl}>")
            continue

        m = re.match(r"^[-*+]\s+(.*)$", stripped)
        if m:
            flush_para()
            if list_open != "ul":
                close_list()
                out.append("<ul>")
                list_open = "ul"
            out.append(f"<li>{_inline(m.group(1))}</li>")
            continue

        m = re.match(r"^\d+[.)]\s+(.*)$", stripped)
        if m:
            flush_para()
            if list_open != "ol":
                close_list()
                out.append("<ol>")
                list_open = "ol"
            out.append(f"<li>{_inline(m.group(1))}</li>")
            continue

        m = re.match(r"^&gt;\s*(.*)$", stripped)
        if m:
            flush_para()
            close_list()
            out.append(f'<blockquote>{_inline(m.group(1))}</blockquote>')
            continue

        para.append(stripped)

    flush_para()
    close_list()
    close_table()
    return "\n".join(out)


