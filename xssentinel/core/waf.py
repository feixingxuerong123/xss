# Status codes typically used by WAFs to indicate blocked requests.
_BLOCK_STATUS = {400, 401, 403, 404, 406, 419, 429, 444, 451, 493, 500, 502,
                 503, 999, 1000}

# Body hints that indicate a WAF block page (English + i18n).
_BLOCK_BODY_HINTS = re.compile(
    r"(request blocked|access denied|forbidden|firewall|security policy|"
    r"malicious|blocked by|not acceptable|waf|"
    r"web application firewall|request rejected|"
    r"suspicious activity|attack detected|"
    r"security rule|rule id|reference id|"
    r"request id|correlation id|incident id|"
    r"access has been blocked|protected by|"
    # Cloudflare-specific
    r"attention required|cf-ray|cloudflare|"
    # ModSecurity-specific
    r"mod_security|this error was generated|"
    # Akamai-specific
    r"akamai|access.denied|"
    # AWS WAF-specific
    r"request blocked by aws|"
    # Imperva-specific
    r"incapsula incident|"
    # Multilingual hints
    r"访问被拒绝|防火墙|安全策略|攻击|恶意请求|"
    r"アクセスが拒否されました|ファイアウォール|"
    r"접근이 거부되었습니다|방화벽|"
    r"Accès refusé|pare-feu|"
    r"Zugriff verweigert|Firewall|"
    r"Acceso denegado|cortafuegos|"
    r"Acesso negado|firewall)",
    re.IGNORECASE,
)

# Status codes that are strong block signals (vs. soft block like 404).
_STRONG_BLOCK_STATUS = {403, 406, 419, 444, 493, 999}


def detect(response) -> dict:
    """Return {'waf': name|None, 'blocked': bool, 'reason': str, 'confidence': str}.

    confidence is one of:
      "high"    -- vendor-specific cookie/header matched
      "medium"  -- body signature matched + block status
      "low"     -- generic block status / generic body hint
    """
    headers_blob = " ".join(f"{k}: {v}" for k, v in response.headers.items())
    cookies_blob = " ".join(v for k, v in response.headers.items()
                            if k.lower() == "set-cookie")
    body_excerpt = (response.text or "")[:8000]

    waf = None
    confidence = "none"
    signal_kind = "any"

    # Pass 1: cookie-based (highest specificity)
    for name, rx, kind in _WAF_SIGNATURES:
        if kind == "cookie" and rx.search(cookies_blob):
            waf = name
            confidence = "high"
            signal_kind = kind
            break
    # Pass 2: header-based
    if not waf:
        for name, rx, kind in _WAF_SIGNATURES:
            if kind in ("header", "any") and rx.search(headers_blob):
                waf = name
                confidence = "high"
                signal_kind = kind
                break
    # Pass 3: body-based
    if not waf:
        for name, rx, kind in _WAF_SIGNATURES:
            if kind in ("body", "any") and rx.search(body_excerpt):
                waf = name
                confidence = "medium"
                signal_kind = kind
                break

    blocked = False
    reason = ""
    if response.status_code in _STRONG_BLOCK_STATUS:
        blocked = True
        reason = f"HTTP {response.status_code}"
    elif response.status_code in _BLOCK_STATUS and waf:
        blocked = True
        reason = f"HTTP {response.status_code} + {waf} signature"
    elif waf and _BLOCK_BODY_HINTS.search(body_excerpt):
        # Phase 122 fix: block-page HINTS are a BODY signal.  This used to
        # search full_blob (headers + body), so the vendor FINGERPRINT
        # headers themselves (Server: cloudflare / CF-RAY) matched the
        # cloudflare/cf-ray hint patterns -- every UNBLOCKED 200 response
        # from any fingerprinted WAF was classified as blocked, and
        # _try_payload then discarded every payload the WAF actually let
        # through (a silent false-negative generator on all WAF'd sites).
        # A real block page carries its hints in the BODY.
        blocked = True
        reason = f"{waf} block page signature"
    elif _BLOCK_BODY_HINTS.search(body_excerpt):
        # Block page hint without a vendor match.
        blocked = True
        reason = "generic block-page body signature"
        if not waf:
            waf = "Generic/Unknown WAF"
            confidence = "low"

    # If a strong block status is present without a vendor match, report
    # generic so the operator knows evasion was triggered.
    if blocked and not waf and response.status_code in _STRONG_BLOCK_STATUS:
        waf = "Generic/Unknown WAF"
        confidence = "low"

    return {
        "waf": waf,
        "blocked": blocked,
        "reason": reason,
        "confidence": confidence,
        "signal": signal_kind if waf else "none",
    }


def detect_from_raw(status_code: int, headers: dict, body: str) -> dict:
    """Detect WAF from raw response components (no Response object needed).

    Useful for async scanners that don't have a requests.Response.
    """
    class _R:
        pass
    r = _R()
    r.status_code = status_code
    r.headers = headers
    r.text = body
    return detect(r)


def list_known_wafs() -> list[str]:
    """Return the list of WAF vendor names known to the detector."""
    seen = []
    for name, _, _ in _WAF_SIGNATURES:
        if name not in seen:
            seen.append(name)
    return seen


def is_waf_signature(text: str) -> str | None:
    """Quick check: does the given text contain any WAF signature?

    Returns the WAF name if matched, else None.
    """
    if not text:
        return None
    for name, rx, _ in _WAF_SIGNATURES:
        if rx.search(text):
            return name
    return None
