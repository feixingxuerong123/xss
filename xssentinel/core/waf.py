"""WAF / filter fingerprinting from response signals.

Detects common blocking signatures so the scanner can adapt (report the WAF,
and the transform engine can prioritize encoding families). This is heuristic
and conservative to avoid false positives.

Detection signals used (in priority order):
  1. Specific response headers (Server, X-Powered-By, Via, X-Cache, etc.)
  2. Vendor-specific cookies (__cfduid, incap_ses, SERVERID, etc.)
  3. Block-page body signatures (vendor error pages, default block messages)
  4. Status code patterns (403, 406, 419, 999, 502-from-WAF, etc.)

The detect() function returns a dict describing the WAF (if any), whether
the request was blocked, and the reason.  Vendors are matched in order of
specificity -- if multiple signals match, the most specific one wins.
"""
